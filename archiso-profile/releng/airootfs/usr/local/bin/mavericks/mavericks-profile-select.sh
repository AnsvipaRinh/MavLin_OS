#!/usr/bin/env bash
# mavericks-profile-select.sh — install-time / firstboot profile selection
# Auto-detects MacBook10,1 via DMI. Unknown hardware → generic.
# Usage: mavericks-profile-select.sh [--profile generic|macbook10,1] [--dry-run]
# Writes /etc/mavericks/profile.conf (sourced by firstboot).
set -euo pipefail

PROFILE_CONF="/etc/mavericks/profile.conf"
PROFILE_STORE="/usr/local/share/mavericks/profiles"
LOG_TAG="[profile-select]"

log() { echo "$LOG_TAG $*"; }
err() { echo "$LOG_TAG ERROR: $*" >&2; }

DRY_RUN=false
MANUAL_PROFILE=""

while [[ $# -gt 0 ]]; do
  case $1 in
    --profile)
      MANUAL_PROFILE="$2"
      shift 2
      ;;
    --dry-run)
      DRY_RUN=true
      shift
      ;;
    *)
      err "Unknown option: $1"
      exit 1
      ;;
  esac
done

detect_model() {
  dmidecode -s system-product-name 2>/dev/null || echo "unknown"
}

MODEL="$(detect_model)"
log "Detected DMI model: $MODEL"

if [[ -n "$MANUAL_PROFILE" ]]; then
  SELECTED_PROFILE="$MANUAL_PROFILE"
  log "Manual override: $SELECTED_PROFILE"
elif [[ "$MODEL" == "MacBook10,1" ]]; then
  SELECTED_PROFILE="macbook10,1"
  log "Auto-detected MacBook10,1 → macbook10,1 profile"
else
  SELECTED_PROFILE="generic"
  log "Non-MacBook / unknown hardware → generic profile"
fi

case "$SELECTED_PROFILE" in
  generic|macbook10,1) ;;
  *)
    err "Unsupported profile: $SELECTED_PROFILE (allowed: generic, macbook10,1)"
    exit 1
    ;;
esac

if [[ "$DRY_RUN" == "true" ]]; then
  log "DRY-RUN: would write profile '$SELECTED_PROFILE' to $PROFILE_CONF"
  log "DRY-RUN: model=$MODEL store=$PROFILE_STORE"
  exit 0
fi

mkdir -p "$(dirname "$PROFILE_CONF")"
cat > "$PROFILE_CONF" <<EOF
# Auto-generated by mavericks-profile-select.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# DO NOT EDIT MANUALLY — re-run profile selection instead.
MAVERICKS_PROFILE="$SELECTED_PROFILE"
MAVERICKS_PROFILE_DIR="$PROFILE_STORE"
MAVERICKS_MODEL="$MODEL"
EOF
log "Profile written: $PROFILE_CONF"
cat "$PROFILE_CONF"
exit 0
