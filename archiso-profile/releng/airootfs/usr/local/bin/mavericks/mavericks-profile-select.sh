#!/usr/bin/env bash
# mavericks-profile-select.sh — Install-time profile selection
# Runs during firstboot or manual invocation. Auto-detects MacBook10,1 via DMI.
# Usage: mavericks-profile-select.sh [--profile generic|macbook10,1] [--dry-run]
# Output: writes selected profile to /etc/mavericks/profile.conf (sourced by firstboot)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
PROFILE_CONF="/etc/mavericks/profile.conf"
MANIFEST_DIR="$REPO_ROOT/configs/profiles"
# Installed ISO path; the runtime must not depend on a repository checkout.
if [[ -d /usr/local/share/mavericks/profiles ]]; then
    MANIFEST_DIR="/usr/local/share/mavericks/profiles"
fi
LOG_TAG="[profile-select]"

log() { echo "$LOG_TAG $*"; }
err() { echo "$LOG_TAG ERROR: $*" >&2; }

DRY_RUN=false
MANUAL_PROFILE=""

# Parse args
while [[ $# -gt 0 ]]; do
    case $1 in
        --profile)
            MANUAL_PROFILE="$2"
            shift 2
            ;;
        --dry-run)
            DRY_RUN=true
            shift
            ;;
        *)
            err "Unknown option: $1"
            exit 1
            ;;
    esac
done

# Auto-detect hardware
detect_model() {
    dmidecode -s system-product-name 2>/dev/null || echo "unknown"
}

MODEL="$(detect_model)"
log "Detected DMI model: $MODEL"

# Determine profile
if [[ -n "$MANUAL_PROFILE" ]]; then
    SELECTED_PROFILE="$MANUAL_PROFILE"
    log "Manual override: $SELECTED_PROFILE"
elif [[ "$MODEL" == "MacBook10,1" ]]; then
    SELECTED_PROFILE="macbook10,1"
    log "Auto-detected MacBook10,1 → macbook10,1 profile"
else
    SELECTED_PROFILE="generic"
    log "Non-MacBook hardware → generic profile"
fi

# Validate profile exists
PROFILE_DIR="$MANIFEST_DIR/$SELECTED_PROFILE"
if [[ ! -d "$PROFILE_DIR" ]]; then
    err "Profile directory not found: $PROFILE_DIR"
    exit 1
fi

# Write profile config (sourced by firstboot)
if [[ "$DRY_RUN" == "true" ]]; then
    log "DRY-RUN: would write profile '$SELECTED_PROFILE' to $PROFILE_CONF"
    log "DRY-RUN: profile dir: $PROFILE_DIR"
else
    mkdir -p "$(dirname "$PROFILE_CONF")"
    cat > "$PROFILE_CONF" <<EOF
# Auto-generated by mavericks-profile-select.sh on $(date)
# DO NOT EDIT MANUALLY — re-run profile selection instead.
MAVERICKS_PROFILE="$SELECTED_PROFILE"
MAVERICKS_PROFILE_DIR="$PROFILE_DIR"
MAVERICKS_MODEL="$MODEL"
EOF
    log "Profile written: $PROFILE_CONF"
    cat "$PROFILE_CONF"
fi

# Graceful degradation summary (logged for audit)
log "=== Graceful Degradation Rules Active ==="
log "  SPI/applespi: Strategy 4 (external USB-C input) always available"
log "  Wi-Fi: brcmfmac baseline + EFI NVRAM detection (no wl unless explicit)"
log "  Audio: speaker-test runtime check → macbook12-audio-driver only if needed"
log "  Bluetooth: in-kernel btusb + bluez always; MacBook driver only if controller missing"
log "  NVMe: pcie_port_pm=off fragment only on MacBook10,1 path (E2 tests removal)"
log "  Display: i915.enable_psr=0 fragment only on MacBook10,1 path (E4/E5 test enable)"
log "  Power: TLP powersave fragment only on MacBook10,1 path"
log "  All fragments: graceful-missing (absent = kernel/default behavior)"

exit 0