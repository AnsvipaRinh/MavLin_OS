#!/usr/bin/env bash
# run-demo.sh — bring up the real MavLinOS desktop in an isolated Xvfb and
# capture presentation screenshots.
#
# WHAT RUNS: the project's real session stack — xfwm4 (Mavericks window
# decorations + compositor), xfdesktop (wallpaper), xfce4-panel (menu bar
# with the mv-apple Apple-menu plugin built from this repo), plank dock
# (Mavericks theme) — plus real mv-* applications from this checkout.
#
# ISOLATION (hard requirement — the dev host is WSLg and DISPLAY=:0 /
# WAYLAND_DISPLAY=wayland-0 leak onto the user's Windows desktop):
#   * scripts/gui-isolation.sh mv_gui_isolate — captures the ambient host
#     display(s) as FORBIDDEN, unsets WAYLAND_DISPLAY, forces GDK_BACKEND=x11,
#     arms the fail-loud sitecustomize guard (HOST-DISPLAY-BLOCKED, exit 125);
#   * the session runs on a dedicated Xvfb display (:98 by default, never the
#     host :0 and never the test-suite-pinned :97);
#   * demo-capture.py independently refuses to capture any display that
#     looks like a host display.
#
# Everything the session needs (theme, panel plugin, rofi themes, desktop
# entries) is staged into <demo-root>/prefix from THIS checkout; the demo
# HOME is generated by make-demo-home.sh. No product file is modified.
#
# Output: artifacts/demo/*.png (next to the repo checkout).
# License: GPL-2.0-or-later.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
DEMO_ROOT="${MV_DEMO_ROOT:-/tmp/opencode/mavlinos-demo}"
DEMO_DISPLAY="${MV_DEMO_DISPLAY:-:98}"
GEOMETRY="${MV_DEMO_GEOMETRY:-1680x1050x24}"
OUT_DIR="$REPO/artifacts/demo"
SHOT_DIR="$DEMO_ROOT/shots"
LOGS="$DEMO_ROOT/logs"
